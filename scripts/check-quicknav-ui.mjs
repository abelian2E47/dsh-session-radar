import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import './build-quicknav-harness.mjs';
import { withFixtureBrowser, settle } from './browser-fixtures.mjs';
const root = path.resolve(import.meta.dirname, '..');
const out = path.join(root, 'test/tmp/quicknav');
fs.mkdirSync(out, { recursive: true });
await withFixtureBrowser(async ({ context }) => {
  const page = context.pages()[0];
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const url = pathToFileURL(path.join(root, 'test/quicknav-harness.html')).href;
  const pref = async (key, value) => { await page.evaluate(([k, v]) => window.__quicknav.controller.setPref(k, v), [key, value]); await settle(page); };
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.goto(url);
  await page.locator('.dsr-quickbar').waitFor();
  await page.getByRole('button', { name: '快捷栏形式与设置', exact: true }).click();
  await page.getByRole('button', { name: '会话卡片', exact: true }).click();
  await page.locator('.dsr-qnav-trigger').waitFor({ state: 'attached' });
  assert.equal(await page.locator('.dsr-quickbar').count(), 0);
  await page.keyboard.press('Escape');
  await page.locator('#composer').focus();
  await page.keyboard.press('Alt+q');
  await page.locator('#dsr-qnav-panel').waitFor();
  assert.equal(await page.locator('.dsr-qnav-card').count(), 7);
  await page.locator('#dsr-qnav-panel').getByRole('button', { name: /^折叠工作区：dsh-dev/ }).click();
  assert.equal(await page.locator('.dsr-qnav-card').count(), 4);
  await page.screenshot({ path: path.join(out, 'cards-right.png') });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#dsr-qnav-panel').count(), 0);
  assert.equal(await page.locator('#composer').evaluate(el => el === document.activeElement), true);
  await pref('quickNavTrigger', 'shortcut');
  await page.locator('.dsr-qnav-trigger').hover();
  await page.waitForTimeout(220);
  assert.equal(await page.locator('#dsr-qnav-panel').count(), 0);
  await page.keyboard.press('Alt+q');
  await page.locator('#dsr-qnav-panel').waitFor();
  await page.keyboard.press('Escape');
  await pref('quickNavTrigger', 'hover');
  await page.mouse.move(700, 600);
  await page.keyboard.press('Alt+q');
  assert.equal(await page.locator('#dsr-qnav-panel').count(), 0);
  await page.locator('.dsr-qnav-trigger').hover();
  await page.locator('#dsr-qnav-panel').waitFor();
  await page.mouse.move(700, 600);
  await page.waitForFunction(() => !document.querySelector('#dsr-qnav-panel'));
  await pref('quickNavCardPosition', 'sidebar-bottom');
  await page.locator('.dsr-qnav-trigger').click();
  await page.locator('#dsr-qnav-panel').waitFor();
  const bottom = await page.locator('#dsr-qnav-panel').boundingBox();
  assert.ok(bottom.x < 30 && bottom.width <= 320);
  await page.locator('#dsr-qnav-panel').getByRole('button', { name: /^展开工作区：dsh-dev/ }).click();
  assert.equal(await page.locator('.dsr-qnav-card').count(), 7);
  await page.screenshot({ path: path.join(out, 'cards-sidebar.png') });
  await pref('quickNavMode', 'icons');
  await pref('quickNavIconLimit', 3);
  await page.locator('.dsr-qnav-more').click();
  await page.locator('.dsr-qnav-overflow').waitFor();
  await page.locator('.dsr-qnav-overflow').getByRole('button', { name: /^折叠工作区：dsh-dev/ }).click();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.dsr-qnav-buttons > .dsr-qnav-group').getAttribute('aria-expanded'), 'false');
  await page.locator('.dsr-qnav-buttons > .dsr-qnav-group').click();
  assert.equal(await page.locator('.dsr-qnav-buttons > .dsr-qnav-group').getAttribute('aria-expanded'), 'true');
  await pref('quickNavIconLimit', 20);
  assert.equal(await page.locator('.dsr-qnav-icon').count(), 7);
  await page.locator('[data-session-id=a1]').hover();
  assert.equal(await page.locator('.dsr-qnav-tooltip').first().isVisible(), true);
  assert.equal(await page.locator('.dsr-qnav-icon__mark').count(), 2);
  await page.locator('[data-session-id=b1]').click();
  assert.equal(await page.evaluate(() => window.__openedSession), 'b1');
  assert.equal(await page.locator('[data-session-id=b1]').getAttribute('aria-current'), 'true');
  await pref('quickNavIconLimit', 4);
  await page.mouse.move(700, 600);
  await page.screenshot({ path: path.join(out, 'icons-top-left.png') });
  await page.getByRole('button', { name: '快捷栏形式与设置', exact: true }).click();
  await page.getByRole('textbox', { name: '当前会话短名' }).fill('模型');
  assert.equal(await page.evaluate(() => window.__quicknav.state.prefs.quickNavLabels.b1), '模型');
  await page.keyboard.press('Escape');
  await pref('quickNavLabels', { a1: '前端' });
  assert.equal(await page.locator('[data-session-id=a1] .dsr-qnav-icon__name').innerText(), '前端');
  await page.reload();
  await page.locator('.dsr-qnav-icon').first().waitFor();
  assert.equal(await page.locator('[data-session-id=a1] .dsr-qnav-icon__name').innerText(), '前端');
  for (const position of ['top-left', 'top-right', 'bottom-left', 'bottom-right', 'custom']) {
    await pref('quickNavIconPosition', position);
    const rect = await page.locator('.dsr-qnav-buttons').boundingBox();
    assert.ok(rect.x >= 0 && rect.y >= 0 && rect.x + rect.width <= 1441 && rect.y + rect.height <= 961, JSON.stringify({ position, rect }));
  }
  const grip = await page.locator('.dsr-qnav-grip').boundingBox();
  await page.mouse.move(grip.x + 5, grip.y + 10);
  await page.mouse.down();
  await page.mouse.move(grip.x + 140, grip.y + 150, { steps: 8 });
  await page.mouse.up();
  assert.ok(await page.evaluate(() => window.__quicknav.state.prefs.quickNavIconPos.x > 0));
  await page.evaluate(() => { document.body.dataset.dsDarkTheme = ''; });
  await pref('quickNavIconPosition', 'top-left');
  await page.getByRole('button', { name: '快捷栏形式与设置', exact: true }).click();
  await page.screenshot({ path: path.join(out, 'icons-settings-dark.png') });
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  await settle(page);
  await page.getByRole('button', { name: '快捷栏形式与设置', exact: true }).click();
  const popup = await page.locator('.dsr-qnav-popover').boundingBox();
  assert.ok(popup.x >= 0 && popup.x + popup.width <= 391 && popup.y >= 0 && popup.y + popup.height <= 845);
  await page.keyboard.press('Escape');
  const mobile = await page.locator('.dsr-qnav-buttons').boundingBox();
  assert.ok(mobile.x >= 0 && mobile.x + mobile.width <= 391);
  await page.screenshot({ path: path.join(out, 'icons-mobile.png') });
  await page.setViewportSize({ width: 1440, height: 960 });
  await pref('quickNavMode', 'mini');
  await page.locator('.dsr-quickbar').waitFor();
  await page.locator('.dsr-quickbar').getByRole('button', { name: /^折叠工作区：dsh-dev/ }).click();
  assert.equal(await page.locator('.dsr-quickbar').getByRole('button', { name: /切换到会话：登录页视觉回归/ }).count(), 0);
  await page.locator('.dsr-quickbar').getByRole('button', { name: /^展开工作区：dsh-dev/ }).click();
  assert.equal(await page.locator('.dsr-quickbar').getByRole('button', { name: /切换到会话：登录页视觉回归/ }).count(), 1);
  await pref('quickNavMode', 'cards');
  await page.evaluate(() => { window.__quicknav.state.entries = []; window.__quicknav.notify(); });
  await page.locator('.dsr-qnav-empty').waitFor();
  assert.ok(await page.getByText('把常用会话放在这里').isVisible());
  await pref('showQuickBar', false);
  assert.equal(await page.locator('.dsr-qnav').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: mode switching, old mini bar, both card positions, shortcut/hover timing, Escape and focus, session navigation, workspace folding in all modes, overflow, alias persistence, drag, dark and mobile layouts; no browser errors.');
});
